# Приводит симметричную матрицу к трёхдиагональному виду
# с помощью отражений Хаусхолдера
import numpy as np

def householder(A):
    A = np.array(A, float)
    n = len(A)
    Q = np.eye(n)                      # накопитель отражений

    for k in range(n - 2):             # последние 2 столбца не трогаем
        x = A[k+1:, k]                 # часть столбца ниже диагонали
        nx = np.linalg.norm(x)         # её норма — будущий поддиагональный элемент
        if nx == 0:                    # уже нулевой — пропускаем
            continue

        # Вектор Хаусхолдера: x ± ||x||·e1, знак выбираем для устойчивости
        v = x + np.copysign(nx, x[0]) * np.eye(1, len(x), 0).ravel()
        v /= np.linalg.norm(v)         # нормируем

        # Строим единичную матрицу и в её правом нижнем блоке
        # размещаем отражение I - 2·v·vᵀ
        H = np.eye(n)
        H[k+1:, k+1:] -= 2 * np.outer(v, v)

        A = H @ A @ H                  # преобразование подобия
        Q = Q @ H                      # накапливаем Q

    return A, Q

A = [[4,1,6,4],[1,2,3,8],[2,0,3,3],[2,1,3,4]]
T, Q = householder(A)
print(np.round(T, 6))
